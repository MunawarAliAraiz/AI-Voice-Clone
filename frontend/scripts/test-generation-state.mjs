import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';
const compiled = ts.transpileModule(readFileSync(new URL('../src/lib/generationState.ts',import.meta.url),'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}});
const exports = {}; runInNewContext(compiled.outputText,{exports});
const base = {submitting:false,converting:false,blocked:false,disabledReason:null,error:null};
const view = changes => exports.generationState({...base,...changes});
assert.equal(view({checkingJob:true}).label,'Checking your generation');
assert.equal(view({jobStatusError:true,checkingJob:true}).state,'error');
assert.equal(view({jobStatusError:true,job:{status:'running'}}).label,'Status unavailable');
assert.equal(view({job:{status:'succeeded',result:null}}).label,'Audio unavailable');
assert.equal(view({job:{status:'succeeded',result:{audio_url:''}}}).state,'error');
assert.equal(view({job:{status:'succeeded',result:{audio_url:'/real-output.wav'}}}).state,'complete');
assert.equal(view({blocked:true,job:{status:'succeeded',result:{audio_url:'/real-output.wav'}}}).state,'blocked');
assert.equal(view({blocked:true,job:{id:2,title:'A real job',status:'running'}}).state,'generating');
assert.equal(view({job:{status:'queued',position:2}}).detail,'Latest generation · Position 3');
assert.equal(view({job:{status:'failed'}}).state,'error');
assert.equal(view({job:{status:'cancelled'}}).state,'paused');
assert.equal(view({submitting:true}).label,'Adding to queue');
assert.equal(view({converting:true}).label,'Converting your script');
assert.equal(view({disabledReason:'Select a voice first.'}).label,'Prepare your script');
assert.equal(view({}).label,'Ready to generate');
console.log('15 real-state status checks passed.');
